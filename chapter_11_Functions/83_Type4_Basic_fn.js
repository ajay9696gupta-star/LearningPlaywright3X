// Type4  with arguments and return value
// Define a function named sumOfTwoNumbers that takes two parameters and returns their sum
function sumOfTwoNumbers(a, b) {
    return a + b;
}

let result = sumOfTwoNumbers(5, 10);
console.log(result); // Output: 15

// some people use this type of function to calculate the sum of two numbers
console.log(sumOfTwoNumbers(5, 10)); // Output: 15